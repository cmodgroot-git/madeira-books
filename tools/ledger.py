#!/usr/bin/env python3
"""Word ledger for Histórias da Madeira.

Counts how often every word has been met across the published books, so each new book can
recycle under-used words and bring in common ones (the project review's two main fixes).

Usage:
  python3 tools/ledger.py                          # write tools/ledger/ledger.md and ledger.json
  python3 tools/ledger.py --draft tools/b18/pages18.json   # also check a draft book against the rules

Rules checked for a draft (see skills/madeira-book-stories, Step 3):
  - recycling: at least 15 under-used words come back (tappable words met 1-2 times, or top-2,000 words met 1-2 times)
  - frequency: at least half of the draft's new tappable words are in the top 2,000
  - readability: at least 80% of the draft's running words already met (books 9-17 scored 73-82%; raise it as the library grows)

A "word" here is a spelling (form): vai, vou and ir count separately. Tappable words are counted by key.
"""
import argparse
import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from extract_stories import read_pages, WORD_RE, BOOK_RE  # noqa: E402

HTML = ROOT / "docs" / "index.html"
OUT = ROOT / "tools" / "ledger"
FREQ = OUT / "pt_top5000.txt"
TOK = re.compile(r"[a-záàâãéêíóôõúüç]+(?:-[a-záàâãéêíóôõúüç]+)*")
# names of people and places are not vocabulary targets
NAMES = {"rita", "ana", "joão", "marta", "tiago", "sofia", "duarte", "inês", "bruno", "funchal", "madeira",
         "seixal", "garajau", "machico", "faial", "calheta", "rabaçal", "lourenço"}


def tokens(text):
    return TOK.findall(WORD_RE.sub(r"\1", text).lower())


def load_freq():
    """word -> (rank, uses per billion words)."""
    rows = [l.split("\t") for l in FREQ.read_text(encoding="utf-8").splitlines() if l and not l.startswith("#")]
    return {w: i + 1 for i, (w, z) in enumerate(rows)}, {w: 10 ** float(z) for w, z in rows}


def build():
    src = HTML.read_text(encoding="utf-8")
    books = BOOK_RE.findall(src)
    form = collections.Counter()          # form -> meetings
    form_books = collections.defaultdict(set)
    first = {}                            # form -> first book
    key = collections.Counter()           # tappable key -> meetings
    key_books = collections.defaultdict(set)
    key_shown = {}
    for num, (book_id, title, n) in enumerate(books, 1):
        for p in read_pages(src, n):
            for shown, k in WORD_RE.findall(p):
                key[k] += 1
                key_books[k].add(num)
                key_shown.setdefault(k, shown)
            for w in tokens(p):
                form[w] += 1
                form_books[w].add(num)
                first.setdefault(w, num)
    return books, form, form_books, first, key, key_books, key_shown


def coverage(form, freq):
    """Share of everyday running text (the top 5,000 forms, weighted by how often each is used) already met."""
    return sum(f for w, f in freq.items() if w in form) / sum(freq.values())


def report(books, form, form_books, first, key, key_books, key_shown, rank, freq):
    nbooks = len(books)
    under_keys = sorted((k for k in key if key[k] <= 2), key=lambda k: (key[k], -max(key_books[k])))
    under_forms = sorted((w for w in form if form[w] <= 2 and w in rank and rank[w] <= 2000 and w not in NAMES),
                         key=lambda w: rank[w])
    missing = [w for w, r in sorted(rank.items(), key=lambda x: x[1]) if r <= 2000 and w not in form]
    tops = {N: sum(1 for w, r in rank.items() if r <= N and w in form) for N in (100, 500, 1000, 2000)}
    lines = [
        "# Word ledger", "",
        f"Books 1–{nbooks}. Generated by `tools/ledger.py` from `docs/index.html`; do not edit by hand.", "",
        "## At a glance", "",
        f"- Running words: {sum(form.values()):,}; different word forms: {len(form):,}; tappable words: {len(key)}",
        f"- Tappable words met once: {sum(1 for k in key if key[k] == 1)}; met 10+ times: {sum(1 for k in key if key[k] >= 10)}",
        f"- Word forms met once: {sum(1 for w in form if form[w] == 1)}; met 10+ times: {sum(1 for w in form if form[w] >= 10)}",
        "- Common words met: " + ", ".join(f"top {N}: {v} ({v * 100 // N}%)" for N, v in tops.items()),
        f"- Estimated share of everyday text already known: {coverage(form, freq) * 100:.0f}% (rough; see pt_top5000.txt header)",
        "",
        "## Tappable words to recycle (met 1–2 times)", "",
        "Pick from the top of this list when writing a new book: they are the closest to being forgotten.", "",
        "| Word | Key | Met | Books |", "| --- | --- | --- | --- |",
    ]
    for k in under_keys:
        lines.append(f"| {key_shown[k]} | `{k}` | {key[k]} | {', '.join(map(str, sorted(key_books[k])))} |")
    lines += ["", "## Common words met only 1–2 times (top 2,000)", "",
              ", ".join(f"{w} ({form[w]}×, #{rank[w]})" for w in under_forms), "",
              "## Common words never met (top 2,000, in frequency order)", "",
              "Some are Brazilian-leaning or hard to show; choose the ones a story can use naturally.", "",
              ", ".join(missing), ""]
    (OUT / "ledger.md").write_text("\n".join(lines), encoding="utf-8")
    data = {
        "books": nbooks,
        "forms": {w: {"met": form[w], "books": sorted(form_books[w]), "first": first[w], "rank": rank.get(w)} for w in sorted(form)},
        "keys": {k: {"met": key[k], "books": sorted(key_books[k]), "shown": key_shown[k]} for k in sorted(key)},
        "missing_top2000": missing,
    }
    (OUT / "ledger.json").write_text(json.dumps(data, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"ledger: {len(form)} forms, {len(key)} keys, {len(under_keys)} keys met 1-2 times, "
          f"{len(missing)} of the top 2,000 never met -> tools/ledger/ledger.md")


def check_draft(path, form, key, key_shown, rank):
    pages = json.loads(Path(path).read_text(encoding="utf-8"))
    toks = [w for p in pages for w in tokens(p)]
    dkeys = [k for p in pages for _, k in WORD_RE.findall(p)]
    new_keys = sorted({k for k in dkeys if k not in key})
    recycled_keys = sorted({k for k in dkeys if 1 <= key.get(k, 0) <= 2})
    recycled_forms = sorted({w for w in toks if 1 <= form.get(w, 0) <= 2 and rank.get(w, 9999) <= 2000 and w not in NAMES})
    new_forms = sorted({w for w in toks if w not in form and w not in NAMES})
    shown = {k: s.lower() for p in pages for s, k in WORD_RE.findall(p)}
    common_new_keys = [k for k in new_keys if any(rank.get(w, 9999) <= 2000 for w in TOK.findall(shown[k]))]
    common_new_forms = [w for w in new_forms if rank.get(w, 9999) <= 2000]
    known_share = sum(1 for w in toks if w in form or w in NAMES) / max(1, len(toks))
    recycled_key_forms = {w for p in pages for sh, k in WORD_RE.findall(p) if k in recycled_keys for w in TOK.findall(sh.lower())}
    recycled = len(recycled_keys) + len(set(recycled_forms) - recycled_key_forms)
    print(f"\nDraft check: {path}")
    print(f"  pages {len(pages)}, running words {len(toks)}, avg {len(toks) / max(1, len(pages)):.0f} per page")
    print(f"  readability: {known_share * 100:.0f}% of running words already met   (rule: >= 80%)")
    print(f"  recycling: {recycled} under-used words come back   (rule: >= 15)")
    print(f"     keys: {', '.join(recycled_keys) or '-'}")
    print(f"     common forms: {', '.join(recycled_forms) or '-'}")
    print(f"  new tappable words: {len(new_keys)}; in the top 2,000: {len(common_new_keys)}   (rule: >= half)")
    print(f"     {', '.join(new_keys)}")
    print(f"  new word forms: {len(new_forms)}; in the top 2,000: {len(common_new_forms)}")
    print(f"     common: {', '.join(common_new_forms) or '-'}")
    print(f"     other:  {', '.join(w for w in new_forms if w not in common_new_forms)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--draft", help="JSON list of a draft book's pages ([shown|key] tags), checked against the ledger")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    rank, freq = load_freq()
    books, form, form_books, first, key, key_books, key_shown = build()
    report(books, form, form_books, first, key, key_books, key_shown, rank, freq)
    if a.draft:
        check_draft(a.draft, form, key, key_shown, rank)


if __name__ == "__main__":
    main()
