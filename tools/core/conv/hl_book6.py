def _strip(pts, w):
    import numpy as _np
    left, right = [], []
    for k in range(len(pts)):
        a = pts[max(0, k - 1)]; b = pts[min(len(pts) - 1, k + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]; L = (dx * dx + dy * dy) ** .5 or 1
        nx, ny = -dy / L * w, dx / L * w
        left.append((pts[k][0] + nx, pts[k][1] + ny)); right.append((pts[k][0] - nx, pts[k][1] - ny))
    return poly(*(left + right[::-1]))
